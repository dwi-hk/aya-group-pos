function normalizeBarcodeName(value = '') {
  return String(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\+/g, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const CATALOG_BY_ID = new Map(
  AYA_BARCODE_CATALOG.map(row => [String(row.id).trim(), row])
);

const SAFE_FALLBACK_IDS = new Set([
  'seblak-all',
  'paket-seblak-es-teh',
  'gado-gado',
  'siomay-telur',
  'sego-sambel-ayam',
  'nasi-kucing',
  'sate-rempelo',
  'es-teh',
  'kopi-hitam'
]);

const rowsByName = new Map();
AYA_BARCODE_CATALOG.forEach(row => {
  const key = normalizeBarcodeName(row.name);
  if (!key) return;
  const list = rowsByName.get(key) || [];
  list.push(row);
  rowsByName.set(key, list);
});

const UNIQUE_CATALOG_BY_NAME = new Map(
  [...rowsByName.entries()]
    .filter(([, rows]) => rows.length === 1)
    .map(([key, rows]) => [key, rows[0]])
);

export function findAyaBarcodeRecord(product = {}) {
  const id = String(product.id || '').trim();
  if (id && CATALOG_BY_ID.has(id)) return CATALOG_BY_ID.get(id);

  const allowNameFallback = product.source === 'fallback' || SAFE_FALLBACK_IDS.has(id);
  if (!allowNameFallback) return null;

  const nameKey = normalizeBarcodeName(product.name || product.nama || '');
  if (!nameKey) return null;
  return UNIQUE_CATALOG_BY_NAME.get(nameKey) || null;
}

export function applyAyaBarcodeCatalog(product = {}) {
  const record = findAyaBarcodeRecord(product);
  if (!record) return product;

  return {
    ...product,
    barcode: record.barcode
  };
}

export function ayaBarcodeCatalogStats() {
  return {
    total: AYA_BARCODE_CATALOG.length,
    uniqueIds: CATALOG_BY_ID.size,
    uniqueNames: UNIQUE_CATALOG_BY_NAME.size,
    ambiguousNames: [...rowsByName.entries()]
      .filter(([, rows]) => rows.length > 1)
      .map(([name, rows]) => ({ name, ids: rows.map(row => row.id) }))
  };
}
